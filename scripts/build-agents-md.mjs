#!/usr/bin/env node
// Build AGENTS.md — the cross-tool entry point for Manifest.
//
// WHY THIS EXISTS
// Manifest's value is the DETERMINISTIC engine (scripts/*.mjs): the gate code,
// the scorecard, verification, tamper-evidence. None of that depends on Claude —
// it's plain Node. AGENTS.md is the open, Linux-Foundation-stewarded standard
// read natively by Codex, Cursor, Copilot, Gemini CLI, Aider, Windsurf and Zed,
// so emitting one makes Manifest usable by teammates who don't have Claude.
//
// The key property this buys: a gate code minted by a PM in Gemini verifies
// identically for a dev in Cursor and for CI, because the code is a hash
// computed by Node — not a model judgement.
//
// SINGLE SOURCE OF TRUTH
// The rubric is imported from ready-check.mjs and the version from
// plugin.json, so AGENTS.md regenerates rather than drifting. Keep it COMPACT:
// it is loaded into context by every tool on every run. Export the core
// PM/dev workflows only — not all 28 skills.
//
// Usage:
//   node scripts/build-agents-md.mjs            # writes ./AGENTS.md
//   node scripts/build-agents-md.mjs --check    # exit 1 if AGENTS.md is stale
//   node scripts/build-agents-md.mjs --out <p>  # custom path
//
// Exit: 0 ok, 1 stale (--check), 2 error.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { RUBRIC } from "./ready-check.mjs";

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));

function version() {
  try {
    return JSON.parse(readFileSync(join(REPO, ".claude-plugin", "plugin.json"), "utf8")).version || "";
  } catch { return ""; }
}

// The rubric table is generated, so adding/renaming an item updates AGENTS.md.
function rubricTable() {
  const rows = RUBRIC.filter((r) => r.req).map(
    (r) => `| \`${r.id}\` | ${r.short || r.name} | ${r.ask || ""} |`
  );
  return ["| id | item | what a good answer looks like |", "|---|---|---|", ...rows].join("\n");
}

function build() {
  const v = version();
  return `# AGENTS.md — Manifest

<!-- GENERATED by scripts/build-agents-md.mjs — do not edit by hand.
     Regenerate: node scripts/build-agents-md.mjs -->

Manifest takes a PRD from spec → build → launch with quality gates. Version ${v}.

**Works in any agent.** The gates are plain Node, so Codex, Cursor, Gemini CLI,
Copilot, Aider, Windsurf, Zed and CI all get identical results. A gate code minted
in one tool verifies in every other — it's a content hash, not a model judgement.

**Ready Check needs nothing installed.** \`scripts/ready-check.mjs\` is a single file
with **zero dependencies** — Node 18+ and that one file is the whole PM-side gate.
(Only the contract/repo tooling — \`validate.mjs\`, \`build-code-context.mjs\` — needs
\`js-yaml\`: \`cd scripts && npm install\`.)

---

## The one rule

**Never hand-write a Ready Check hand-off, scorecard, or gate code.** Always run the
CLI and use its output verbatim. A hand-written block looks official and proves
nothing — \`--verify\` reports \`UNVERIFIABLE\` because the \`• [id] …\` item list it
hashes isn't there. Same for the score: run \`--scorecard\`, don't estimate it.

---

## Ready Check — the PM gate (before dev grooming)

Score a PRD against the Definition of Ready, then mint a tamper-evident hand-off.

\`\`\`bash
node scripts/ready-check.mjs --scorecard answers.json     # panel-like status
node scripts/ready-check.mjs --check     answers.json     # verdict JSON (exit 1 if not ready)
node scripts/ready-check.mjs --handoff   answers.json freeze.json   # hand-off + freeze stamp
\`\`\`

\`answers.json\`:

\`\`\`json
{ "title": "<feature>",
  "items": {
    "goal":   { "detail": "..." },
    "design": { "na": true, "reason": "why it genuinely doesn't apply" },
    "metric": { "waived": true, "reason": "why it can't be answered yet" }
  } }
\`\`\`

**Workflow:** read the PRD (fetch the link if you can) → map it to the items below →
run \`--scorecard\` → show it → ask only for the gaps → fold the replies in → re-run
until it clears → then \`--handoff\`.

### The 11 required items

${rubricTable()}

Also recommended (never blocking): \`deps\`, \`rollout\`.

### Rules the engine enforces

- **N/A needs a reason.** A bare \`{"na": true}\` does not clear an item; the reason is
  hashed into the gate code and shown to dev. Only \`design\`, \`oldbeh\`, \`states\`,
  \`writer\` are skippable at all.
- **Stack-neutral.** Backend/API/data PRDs answer the same items the backend way —
  \`design\` = interface/contract spec, \`states\` = response & status codes, \`flows\` =
  endpoints/jobs. There is no "backend → skip it" path.
- **Waivers** (\`{"waived": true, "reason": "..."}\`) clear an item but are surfaced for
  dev to accept or push back.

---

## Verifying a hand-off (any tool, no panel)

\`\`\`bash
node scripts/ready-check.mjs --verify <ticket-or-block>.txt
\`\`\`

Accepts a whole ticket/page dump — it finds the block inside, so nobody hand-copies.

| Result | Meaning |
|---|---|
| \`VALID\` | answers are exactly what was signed off |
| \`STALE\` | edited after the code was minted → ask for a fresh check |
| \`INVALID\` | not a real gate code |
| \`UNVERIFIABLE\` | no item list — the block wasn't produced by \`--handoff\`. Treat as **no gate**. |

A gate code **alone** can never be verified: it's a hash of the answers, so without
the item list there's nothing to check it against.

**Drift check** (did the PRD or design change after sign-off?):

\`\`\`bash
node scripts/ready-check.mjs --hash <prd-body>.txt          # content pin for the source
node scripts/ready-check.mjs --verify-freeze <block>.txt current.json
\`\`\`

→ \`VALID\` / \`STALE-SOURCE\` / \`STALE-DESIGN\` / \`STALE-CONTENT\`. \`--hash\` ignores any
Ready Check addendum, so writing answers back into the PRD never counts as drift.

---

## Keep the PRD complete (don't strand answers in chat)

When someone answers a gap in conversation, that answer must go back into the PRD —
otherwise a dev reading the doc never sees it.

\`\`\`bash
node scripts/ready-check.mjs --addendum answers.json "<author>"
\`\`\`

Renders only the items flagged \`"addedInReview": true\`. **Append** it to the source
page/ticket — never overwrite. Do this **before** minting the hand-off, then re-read
the source version, so your own edit can't trigger a false \`STALE-SOURCE\`.

---

## Contracts (dev side)

\`\`\`bash
node scripts/validate.mjs .manifest/contracts/<ID>.md    # deterministic contract check
node scripts/build-code-context.mjs                       # refresh the cross-repo cache
\`\`\`

Contracts live as markdown in \`.manifest/contracts/\`; findings are written alongside.
Git is the audit trail — no external database.

**Pick the path by risk:** typo → just commit · one-line fix → express lane ·
new behavior → full contract · breaking change/migration → decompose into children.

---

## Repo layout

| Path | What |
|---|---|
| \`scripts/*.mjs\` | deterministic engine — the portable core |
| \`reference/READY-CHECK-RUBRIC.md\` | the Definition of Ready in full |
| \`.manifest/repos.yml\` | repos scanned for cross-repo context |
| \`.manifest/contracts/\` | contracts + findings |
| \`gate/prd-readiness-gate.html\` | offline gate — same rubric, plain browser, no AI |
| \`skills/\` | the long-form playbooks (richest in Claude Code / Cowork) |

Anyone without an AI tool at all can still clear the gate with the offline HTML page;
it mints the same code format and verifies everywhere.
`;
}

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const OUT = outIdx >= 0 ? args[outIdx + 1] : join(REPO, "AGENTS.md");
const content = build();

if (args.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== content) {
    console.error("AGENTS.md is stale — run: node scripts/build-agents-md.mjs");
    process.exit(1);
  }
  console.log("AGENTS.md up to date.");
} else {
  writeFileSync(OUT, content);
  console.log(`AGENTS.md written (${content.split("\n").length} lines) → ${OUT}`);
}
